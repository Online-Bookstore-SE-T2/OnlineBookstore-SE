"""Write the Markdown summary of a pytest run over the JavaScript suites."""

from __future__ import annotations

import os
import subprocess
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from js_suites import REPO_ROOT, Case, SuiteRun

_FAILURE_LINES = 40
_RESULT_LABEL = {"passed": "passed", "failed": "**FAILED**", "skipped": "skipped"}


def write(path: Path, runs: list[SuiteRun], outcomes: list[tuple[Case, str]], exit_status: int) -> None:
    by_suite: dict[str, list[tuple[Case, str]]] = {}
    for case, outcome in outcomes:
        by_suite.setdefault(case.suite.key, []).append((case, outcome))
    totals = Counter(outcome for _, outcome in outcomes)
    failures = [case for case, outcome in outcomes if outcome == "failed"]

    if exit_status == 0:
        result = "**PASSED**"
    elif exit_status == 1:
        result = "**FAILED**"
    else:
        result = f"**ERROR** (pytest exit status {exit_status})"

    lines = [
        "# CI test results",
        "",
        "This file is regenerated by the CI workflow (`.github/workflows/ci.yml`) after every "
        "push to `main` and overwritten each time, so it always describes the latest run. "
        "Earlier results are in this file's git history. Do not edit it by hand.",
        "",
        "| | |",
        "|---|---|",
        f"| Result | {result}: {len(outcomes)} tests, {totals['passed']} passed, "
        f"{totals['failed']} failed, {totals['skipped']} skipped |",
        *_metadata_rows(),
        "| Command | `python -m pytest`, which runs `npm test -w server` (Jest) and "
        "`npm test -w client` (Vitest) |",
        "",
        "## Suites",
        "",
        "| Suite | Runner | Passed | Failed | Skipped | Total | Time |",
        "|---|---|--:|--:|--:|--:|--:|",
    ]
    for run in runs:
        counts = Counter(outcome for _, outcome in by_suite.get(run.suite.key, []))
        lines.append(
            f"| {run.suite.title} | {run.suite.runner} | {counts['passed']} | {counts['failed']} | "
            f"{counts['skipped']} | {sum(counts.values())} | {run.seconds:.1f} s |"
        )
    lines.append(
        f"| **All** | | **{totals['passed']}** | **{totals['failed']}** | **{totals['skipped']}** | "
        f"**{len(outcomes)}** | {sum(run.seconds for run in runs):.1f} s |"
    )

    lines += ["", "## Failures", ""]
    if not failures:
        lines.append("None.")
    for case in failures:
        lines += [
            f"### {case.suite.title}: {_escape(case.name)}",
            "",
            f"`{case.file}`" if case.file else f"{case.suite.runner} run",
            "",
            "````text",
            _truncate(case.message or "No failure message was reported."),
            "````",
            "",
        ]

    lines += ["", "## All test cases", ""]
    for run in runs:
        suite_outcomes = by_suite.get(run.suite.key, [])
        files = {case.file for case, _ in suite_outcomes if case.file}
        lines += [
            "<details>",
            f"<summary><strong>{run.suite.title} ({run.suite.runner})</strong>: "
            f"{len(suite_outcomes)} tests in {len(files)} files</summary>",
            "",
            "| File | Test | Result | Time |",
            "|---|---|---|--:|",
        ]
        for case, outcome in sorted(suite_outcomes, key=lambda pair: pair[0].file):
            duration = "" if case.duration_ms is None else f"{case.duration_ms:.0f} ms"
            lines.append(
                f"| `{case.file or '-'}` | {_escape(case.name)} | {_RESULT_LABEL.get(outcome, outcome)} | {duration} |"
            )
        lines += ["", "</details>", ""]

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8", newline="\n")


def _metadata_rows() -> list[str]:
    server = os.environ.get("GITHUB_SERVER_URL")
    repository = os.environ.get("GITHUB_REPOSITORY")
    sha = os.environ.get("GITHUB_SHA") or _git("rev-parse", "HEAD")
    subject = _git("log", "-1", "--format=%s", sha) if sha else ""

    rows = []
    if sha:
        short = f"`{sha[:7]}`"
        if server and repository:
            short = f"[{short}]({server}/{repository}/commit/{sha})"
        rows.append(f"| Commit | {short} {_escape(subject)} |")

    run_id = os.environ.get("GITHUB_RUN_ID")
    if run_id and server and repository:
        attempt = os.environ.get("GITHUB_RUN_ATTEMPT", "1")
        event = os.environ.get("GITHUB_EVENT_NAME", "")
        ref = os.environ.get("GITHUB_REF_NAME", "")
        rows.append(
            f"| Run | [GitHub Actions run {run_id}, attempt {attempt}]"
            f"({server}/{repository}/actions/runs/{run_id}) ({event} to `{ref}`) |"
        )
    else:
        rows.append("| Run | Local run, not from CI |")

    finished = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    rows.append(f"| Finished | {finished} |")
    return rows


def _git(*args: str) -> str:
    try:
        return subprocess.run(
            ["git", *args], cwd=REPO_ROOT, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def _escape(text: str) -> str:
    """Make text safe inside a Markdown table cell or heading."""
    return (
        text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        .replace("|", "\\|").replace("\n", " ")
    )


def _truncate(message: str) -> str:
    lines = message.splitlines()
    if len(lines) <= _FAILURE_LINES:
        return message
    hidden = len(lines) - _FAILURE_LINES
    return "\n".join(lines[:_FAILURE_LINES] + [f"... {hidden} more lines in the CI log"])
